// negative zero, or either extreme of the exponent range. This test closes that gap: every
// code, against goldens taken from torch's own float8_e4m3fn / float8_e8m0fnu, compared as
// BIT PATTERNS so that -0.0 vs +0.0 is a failure rather than a tie.
