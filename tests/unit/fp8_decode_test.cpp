// Written because the Phase 2 gate found criterion 4's coverage narrower than its wording:
// `layers.0.attn.wq_b.weight` happens to contain 254 of 256 E4M3 codes, and the two it is
// missing are exactly the NaN encodings; its E8M0 scale plane carries only four distinct
