// Encode a Unicode codepoint as UTF-8 (≤ 4 bytes, sufficient for codepoints up to 0x10FFFF).
std::string encode_codepoint(int cp) {
    std::string s;
    if (cp < 0x80) {
        s.push_back(char(cp));
    } else if (cp < 0x800) {
        s.push_back(char(0xC0 | (cp >> 6)));
        s.push_back(char(0x80 | (cp & 0x3F)));
    } else if (cp < 0x10000) {
        s.push_back(char(0xE0 | (cp >> 12)));
        s.push_back(char(0x80 | ((cp >> 6) & 0x3F)));
        s.push_back(char(0x80 | (cp & 0x3F)));
    } else {
        s.push_back(char(0xF0 | (cp >> 18)));
        s.push_back(char(0x80 | ((cp >> 12) & 0x3F)));
        s.push_back(char(0x80 | ((cp >> 6) & 0x3F)));
        s.push_back(char(0x80 | (cp & 0x3F)));
    }
    return s;
}

// Length (in bytes) of the UTF-8 codepoint starting at byte `c`.
inline size_t utf8_len(unsigned char c) {
    if      ((c & 0x80) == 0)    return 1;
    else if ((c & 0xE0) == 0xC0) return 2;
    else if ((c & 0xF0) == 0xE0) return 3;
    else if ((c & 0xF8) == 0xF0) return 4;
    return 1;  // invalid; treat as ASCII to make progress
}

// "Letter"-ish predicate for pretokenization. ASCII alpha + any non-ASCII byte
// (treated as letter for simplification — won't be perfectly HF-compatible
// across script boundaries but round-trips OK).
inline bool is_letter_byte(unsigned char c) {
    return (c >= 'A' && c <= 'Z') || (c >= 'a' && c <= 'z') || (c >= 0x80);
}
inline bool is_digit_byte(unsigned char c) { return c >= '0' && c <= '9'; }
inline bool is_space_byte(unsigned char c) { return c == ' ' || c == '\t' || c == '\n' || c == '\r'; }

// ---- Unicode classes for the joyai-llm pre-tokenizer ----------------------
//
// llama.cpp runs the joyai regex set through its GENERIC split path, which first
// "collapses" every codepoint to a single byte (unicode.cpp unicode_regex_split):
//   is_whitespace          -> 0x0B, matched by \s
//   category N / L / P / M / S -> 0xD1 / 0xD2 / 0xD3 / 0xD4 / 0xD5
//   anything else (Z, C, undefined) -> 0xD0
// and codepoints < 128 are left as themselves. The seven classes below are that
// collapsed alphabet, so matching on them reproduces the reference exactly.
enum UniCls : uint8_t { kUOther = 0, kUNum, kULet, kUPun, kUMrk, kUSym, kUWs };

// ASCII half. This is NOT plain Unicode: it is llama.cpp's k_ucat_map, i.e. the
// sub-128 members it puts in each collapsed class. Note '~' (0x7E) is in NEITHER
// \p{P} nor \p{S} there (upstream's map omits it) — replicated deliberately so
// the split matches the reference byte for byte.
struct AsciiClsTable {
    UniCls c[128] = {};
    constexpr AsciiClsTable() {
        for (int i = 0; i < 128; ++i) c[i] = kUOther;
        c[0x09] = c[0x0A] = c[0x0B] = c[0x0C] = c[0x0D] = c[0x20] = kUWs;
        for (int i = '0'; i <= '9'; ++i) c[i] = kUNum;
        for (int i = 'A'; i <= 'Z'; ++i) c[i] = kULet;
        for (int i = 'a'; i <= 'z'; ++i) c[i] = kULet;
        // k_ucat_map PUNCTUATION: !-# %-* ,-/ :-; ?-@ [-] _ { }
        for (int i = 0x21; i <= 0x23; ++i) c[i] = kUPun;
        for (int i = 0x25; i <= 0x2A; ++i) c[i] = kUPun;
        for (int i = 0x2C; i <= 0x2F; ++i) c[i] = kUPun;
        for (int i = 0x3A; i <= 0x3B; ++i) c[i] = kUPun;
        for (int i = 0x3F; i <= 0x40; ++i) c[i] = kUPun;
        for (int i = 0x5B; i <= 0x5D; ++i) c[i] = kUPun;
        c[0x5F] = c[0x7B] = c[0x7D] = kUPun;
        // k_ucat_map SYMBOL: $ + <-> ^ ` |   ('~' deliberately absent)
        c[0x24] = c[0x2B] = c[0x5E] = c[0x60] = c[0x7C] = kUSym;
        for (int i = 0x3C; i <= 0x3E; ++i) c[i] = kUSym;
    }
};
