// Serialize like Python's json.dumps(..., ensure_ascii=False): compact but with
// ", " between items and ": " after keys. nlohmann's own dump() omits both
// spaces, which would not byte-match the reference tool schemas.
void ds4_json_dump_py(const nlohmann::ordered_json& j, std::string& out) {
    if (j.is_object()) {
        out += '{';
        bool first = true;
        for (auto it = j.begin(); it != j.end(); ++it) {
            if (!first) out += ", ";
            first = false;
            out += nlohmann::ordered_json(it.key()).dump(-1, ' ', /*ensure_ascii=*/false);
            out += ": ";
            ds4_json_dump_py(it.value(), out);
        }
        out += '}';
    } else if (j.is_array()) {
        out += '[';
        bool first = true;
        for (const auto& e : j) {
            if (!first) out += ", ";
            first = false;
            ds4_json_dump_py(e, out);
        }
        out += ']';
    } else {
        out += j.dump(-1, ' ', /*ensure_ascii=*/false);
    }
}

