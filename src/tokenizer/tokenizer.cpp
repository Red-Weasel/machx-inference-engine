// _read_until_stop(): scan from `i` for the earliest of `stops`. Returns the
// index just past the match (or npos-as-end), fills `before`, and sets `matched`
// to the index into `stops` (-1 when none matched).
size_t ds4_read_until(size_t i, std::string_view text,
                      std::span<const std::string_view> stops,
                      std::string_view& before, int& matched) {
    size_t best = text.size();
    matched = -1;
    for (size_t k = 0; k < stops.size(); ++k) {
        const size_t p = text.find(stops[k], i);
        if (p != std::string_view::npos && p < best) { best = p; matched = int(k); }
    }
    before = text.substr(i, best - i);
    return matched < 0 ? text.size() : best + stops[size_t(matched)].size();
}

// Python `$` (no re.MULTILINE) matches at end of string OR immediately before a
// newline that ends the string. Both anchors are live, and the `(.*?)` groups in
// front of them are non-greedy, so the EARLIER anchor is preferred. Returns the
// candidate offsets that `$` can sit at, earliest first.
std::pair<size_t, size_t> ds4_dollar_ends(std::string_view s) {
    if (!s.empty() && s.back() == '\n') return {s.size() - 1, s.size()};
    return {s.size(), s.size()};
}

// r'^\s*name="(.*?)">\n$' — the invoke header.
bool ds4_parse_invoke_name(std::string_view seg, std::string& name) {
    size_t b = 0;
    while (b < seg.size() && (seg[b] == ' ' || seg[b] == '\t' || seg[b] == '\n' ||
                              seg[b] == '\r' || seg[b] == '\v' || seg[b] == '\f')) ++b;
    static constexpr std::string_view kPfx = "name=\"";
    if (seg.substr(b, kPfx.size()) != kPfx) return false;
    b += kPfx.size();
    static constexpr std::string_view kSfx = "\">\n";
    const auto ends = ds4_dollar_ends(seg);
    for (const size_t e : {ends.first, ends.second}) {
        if (e < b + kSfx.size()) continue;
        if (seg.substr(e - kSfx.size(), kSfx.size()) != kSfx) continue;
        name.assign(seg.substr(b, e - kSfx.size() - b));
        return true;
    }
    return false;
}

// r'^ name="(.*?)" string="(true|false)">(.*?)<$' — one DSML parameter.
bool ds4_parse_param(std::string_view seg, std::string& key, bool& is_str, std::string& val) {
    static constexpr std::string_view kPfx = " name=\"";
    static constexpr std::string_view kMid = "\" string=\"";
    if (seg.substr(0, kPfx.size()) != kPfx) return false;
    const auto ends = ds4_dollar_ends(seg);
    // Non-greedy name group: try each `" string="` left to right.
    for (size_t m = seg.find(kMid, kPfx.size()); m != std::string_view::npos;
         m = seg.find(kMid, m + 1)) {
        size_t p = m + kMid.size();
        bool s;
        if      (seg.substr(p, 6) == "true\">")  { s = true;  p += 6; }
        else if (seg.substr(p, 7) == "false\">") { s = false; p += 7; }
        else continue;
        for (const size_t e : {ends.first, ends.second}) {
            if (e < p + 1 || seg[e - 1] != '<') continue;
            key.assign(seg.substr(kPfx.size(), m - kPfx.size()));
            is_str = s;
            val.assign(seg.substr(p, e - 1 - p));
            return true;
        }
    }
    return false;
}

