constexpr size_t kUniRangeCount = sizeof(kUniRanges) / sizeof(kUniRanges[0]);

inline UniCls uni_class(uint32_t cp) {
    if (cp < 128) return kAsciiCls.c[cp];
    if (cp >= 0x110000) return kUOther;   // past MAX_CODEPOINTS → UNDEFINED upstream
    // Find the last entry whose start <= cp.
    size_t lo = 0, hi = kUniRangeCount;
    while (lo + 1 < hi) {
        const size_t mid = (lo + hi) / 2;
        if ((kUniRanges[mid] >> 3) <= cp) lo = mid; else hi = mid;
    }
    return UniCls(kUniRanges[lo] & 7u);
}

// Decode one UTF-8 codepoint at `i`. Returns the codepoint and advances `i`.
// Malformed bytes yield the raw byte value and consume one byte — the engine
// keeps raw bytes for BPE, where llama.cpp substitutes U+FFFD (see the
// pretokenize_joyai comment).
inline uint32_t utf8_decode(std::string_view s, size_t& i) {
    const unsigned char c0 = uint8_t(s[i]);
    const size_t n = utf8_len(c0);
    if (n == 1 || i + n > s.size()) { ++i; return c0; }
    uint32_t cp = c0 & (0xFFu >> (n + 1));
    for (size_t k = 1; k < n; ++k) {
        const unsigned char ck = uint8_t(s[i + k]);
        if ((ck & 0xC0) != 0x80) { ++i; return c0; }   // truncated sequence
        cp = (cp << 6) | (ck & 0x3F);
    }
    i += n;
    return cp;
}

// joyai regex 2: "[一-龥぀-ゟ゠-ヿ]+" — CJK Unified Ideographs U+4E00..U+9FA5
// plus Hiragana U+3040..U+309F and Katakana U+30A0..U+30FF (contiguous).
inline bool is_joyai_cjk(uint32_t cp) {
    return (cp >= 0x3040 && cp <= 0x30FF) || (cp >= 0x4E00 && cp <= 0x9FA5);
}

